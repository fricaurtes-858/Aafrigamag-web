/*
# Contact form attachments (private)

Extends the existing contact_messages table and adds private file attachments
sent by visitors through the contact form. These attachments are PRIVATE: only
the authenticated administrator can read or download them. Visitors can only
upload (INSERT) and create their message; they cannot list, read, or download
any attachments, including their own after upload.

## Changes
1. ALTER contact_messages: add `phone` (optional) and `subject` columns.
   (Non-destructive: nullable columns with safe defaults.)
2. New table contact_attachments: one row per uploaded file, linked to a
   contact message. Cascades on message delete.
3. New PRIVATE storage bucket `contact-attachments` (public = false).
   - anon/authenticated can INSERT (upload) objects only.
   - Only authenticated admins (is_admin()) can SELECT and DELETE objects.
   - No public read. Visitors must use signed URLs generated by the admin.

## Security
- RLS on contact_attachments: public INSERT only (linked to a message);
  admin-only SELECT and DELETE.
- Storage bucket is private; no SELECT policy for anon, so direct public URLs
  return 400/PrivateResourceError. Admin access is via signed URLs.
- File names are namespaced by message id + random key to avoid collisions and
  path guessing.

## Non-destructive
- Does NOT modify existing rows, policies, buckets, or other tables.
- Only adds columns and one new table + bucket.
*/

-- 1. Add optional phone and subject to contact messages
ALTER TABLE public.contact_messages
  ADD COLUMN IF NOT EXISTS phone text,
  ADD COLUMN IF NOT EXISTS subject text;

-- 2. Contact attachments table
CREATE TABLE IF NOT EXISTS public.contact_attachments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  message_id uuid NOT NULL REFERENCES public.contact_messages(id) ON DELETE CASCADE,
  storage_path text NOT NULL,
  original_name text NOT NULL,
  mime_type text NOT NULL DEFAULT 'application/octet-stream',
  size_bytes bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS contact_attachments_message_idx ON public.contact_attachments(message_id);

ALTER TABLE public.contact_attachments ENABLE ROW LEVEL SECURITY;

GRANT INSERT ON public.contact_attachments TO anon, authenticated;
GRANT SELECT, DELETE ON public.contact_attachments TO authenticated;

DROP POLICY IF EXISTS "contact_attachments_public_insert" ON public.contact_attachments;
CREATE POLICY "contact_attachments_public_insert"
  ON public.contact_attachments FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    EXISTS (SELECT 1 FROM public.contact_messages m WHERE m.id = contact_attachments.message_id)
  );

DROP POLICY IF EXISTS "contact_attachments_admin_select" ON public.contact_attachments;
CREATE POLICY "contact_attachments_admin_select"
  ON public.contact_attachments FOR SELECT
  TO authenticated
  USING (public.is_admin());

DROP POLICY IF EXISTS "contact_attachments_admin_delete" ON public.contact_attachments;
CREATE POLICY "contact_attachments_admin_delete"
  ON public.contact_attachments FOR DELETE
  TO authenticated
  USING (public.is_admin());

-- 3. Private storage bucket for contact attachments
INSERT INTO storage.buckets (id, name, public)
VALUES ('contact-attachments', 'contact-attachments', false)
ON CONFLICT (id) DO NOTHING;

-- Visitors can upload only; path must be under contact-attachments/
DROP POLICY IF EXISTS "contact_attachments_storage_public_insert" ON storage.objects;
CREATE POLICY "contact_attachments_storage_public_insert"
  ON storage.objects FOR INSERT
  TO anon, authenticated
  WITH CHECK (bucket_id = 'contact-attachments');

-- Admin can read (needed to generate signed URLs and view)
DROP POLICY IF EXISTS "contact_attachments_storage_admin_select" ON storage.objects;
CREATE POLICY "contact_attachments_storage_admin_select"
  ON storage.objects FOR SELECT
  TO authenticated
  USING (bucket_id = 'contact-attachments' AND public.is_admin());

-- Admin can delete
DROP POLICY IF EXISTS "contact_attachments_storage_admin_delete" ON storage.objects;
CREATE POLICY "contact_attachments_storage_admin_delete"
  ON storage.objects FOR DELETE
  TO authenticated
  USING (bucket_id = 'contact-attachments' AND public.is_admin());
